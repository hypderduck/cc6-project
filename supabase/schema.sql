-- Wildwatch NTU: Supabase schema (prototype).
-- Run this once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
--
-- WARNING: the row-level-security policies below let ANYONE with the anon key
-- read, insert, update and delete. That is fine for a showcase prototype with
-- mock data and no auth. Lock them down before collecting real reports.

create table if not exists public.reports (
  id            bigint generated by default as identity (start with 1000) primary key,
  ts            timestamptz not null,
  type          text not null check (type in ('sighting', 'injury', 'fatality')),
  species       text not null,
  hs            text not null,
  lat           double precision not null,
  lng           double precision not null,
  elsewhere     boolean not null default false,
  night         boolean not null default false,
  poor_light    boolean not null default false,
  wet           boolean not null default false,
  heavy_traffic boolean not null default false,
  forest_edge   boolean not null default false,
  wrong_place   boolean not null default false,
  photo         boolean not null default false,
  reporter      text not null default 'Anonymous',
  status        text not null default 'pending' check (status in ('pending', 'verified', 'rejected')),
  client_id     text,
  likes         integer not null default 0 check (likes >= 0),
  created_at    timestamptz not null default now()
);

create index if not exists reports_ts_idx on public.reports (ts desc);

create table if not exists public.comments (
  id         bigint generated by default as identity primary key,
  report_id  bigint not null references public.reports (id) on delete cascade,
  name       text not null,
  text       text not null check (char_length(text) between 1 and 280),
  ts         timestamptz not null default now(),
  client_id  text,
  flagged    boolean not null default false,
  demo       boolean not null default false
);

create index if not exists comments_report_idx on public.comments (report_id);

-- Atomic like counter.
create or replace function public.bump_likes(p_report_id bigint, p_delta integer)
returns integer
language sql
security definer
set search_path = public
as $$
  update public.reports
     set likes = greatest(0, likes + sign(p_delta)::integer)
   where id = p_report_id
  returning likes;
$$;

grant execute on function public.bump_likes(bigint, integer) to anon, authenticated;

-- Demo-only open policies (see warning above).
alter table public.reports  enable row level security;
alter table public.comments enable row level security;

drop policy if exists "demo read reports"   on public.reports;
drop policy if exists "demo write reports"  on public.reports;
drop policy if exists "demo read comments"  on public.comments;
drop policy if exists "demo write comments" on public.comments;

create policy "demo read reports"   on public.reports  for select using (true);
create policy "demo write reports"  on public.reports  for all    using (true) with check (true);
create policy "demo read comments"  on public.comments for select using (true);
create policy "demo write comments" on public.comments for all    using (true) with check (true);

-- Realtime, so the admin dashboard updates live across devices.
do $$
begin
  alter publication supabase_realtime add table public.reports;
exception when duplicate_object then null;
end $$;

do $$
begin
  alter publication supabase_realtime add table public.comments;
exception when duplicate_object then null;
end $$;
